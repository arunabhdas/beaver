//! `beaver.lock`: deterministic, sorted TOML.

use crate::manifest::Version;
use beaver_source::Diagnostic;
use serde::Deserialize;
use std::fmt::Write as _;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Source {
    /// Normalized registry base URL.
    Registry(String),
    /// Path relative to the root package, as written in the manifest chain.
    Path(String),
}

impl Source {
    pub fn render(&self) -> String {
        match self {
            Source::Registry(u) => format!("registry+{u}"),
            Source::Path(p) => format!("path+{p}"),
        }
    }

    pub fn parse(s: &str) -> Option<Source> {
        if let Some(u) = s.strip_prefix("registry+") {
            Some(Source::Registry(u.to_string()))
        } else {
            s.strip_prefix("path+").map(|p| Source::Path(p.to_string()))
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    pub version: Version,
    pub source: Source,
    /// SHA-256 of the compressed archive (registry packages only).
    pub checksum: Option<String>,
    /// Exact direct dependencies as `name@version`, sorted.
    pub dependencies: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Lockfile {
    /// Sorted by name (names are unique within a graph).
    pub packages: Vec<LockedPackage>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawLock {
    lock_version: i64,
    #[serde(default)]
    package: Vec<RawLocked>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawLocked {
    name: String,
    version: String,
    source: String,
    checksum: Option<String>,
    #[serde(default)]
    dependencies: Vec<String>,
}

pub fn is_sha256_hex(s: &str) -> bool {
    s.len() == 64
        && s.bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

fn quote(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

impl Lockfile {
    pub fn get(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    pub fn render(&self) -> String {
        let mut pkgs = self.packages.clone();
        pkgs.sort_by(|a, b| a.name.cmp(&b.name));
        let mut out = String::from(
            "# This file is generated by `beaver`. Do not edit it by hand.\nlock_version = 1\n",
        );
        for p in &pkgs {
            let mut deps = p.dependencies.clone();
            deps.sort();
            let _ = write!(
                out,
                "\n[[package]]\nname = {}\nversion = {}\nsource = {}\n",
                quote(&p.name),
                quote(&p.version.to_string()),
                quote(&p.source.render())
            );
            if let Some(c) = &p.checksum {
                let _ = writeln!(out, "checksum = {}", quote(c));
            }
            let deps: Vec<String> = deps.iter().map(|d| quote(d)).collect();
            let _ = writeln!(out, "dependencies = [{}]", deps.join(", "));
        }
        out
    }

    pub fn parse(text: &str) -> Result<Lockfile, Diagnostic> {
        let err = |m: String| {
            Diagnostic::global("B6010", format!("beaver.lock: {m}"))
                .with_help("delete beaver.lock and run `beaver fetch` to regenerate it")
        };
        let raw: RawLock =
            toml::from_str(text).map_err(|e| err(format!("invalid lockfile: {}", e.message())))?;
        if raw.lock_version != 1 {
            return Err(err(format!(
                "unsupported lock_version {}",
                raw.lock_version
            )));
        }
        let mut packages = Vec::new();
        for r in raw.package {
            crate::manifest::validate_name(&r.name).map_err(err)?;
            let version = Version::parse(&r.version).map_err(err)?;
            let source = Source::parse(&r.source)
                .ok_or_else(|| err(format!("invalid source `{}`", r.source)))?;
            match (&source, &r.checksum) {
                (Source::Registry(_), Some(c)) if is_sha256_hex(c) => {}
                (Source::Registry(_), _) => {
                    return Err(err(format!(
                        "registry package `{}` needs a valid SHA-256 checksum",
                        r.name
                    )))
                }
                (Source::Path(_), None) => {}
                (Source::Path(_), Some(_)) => {
                    return Err(err(format!(
                        "path package `{}` must not have a checksum",
                        r.name
                    )))
                }
            }
            for d in &r.dependencies {
                let ok = d
                    .split_once('@')
                    .map(|(n, v)| {
                        crate::manifest::validate_name(n).is_ok() && Version::parse(v).is_ok()
                    })
                    .unwrap_or(false);
                if !ok {
                    return Err(err(format!("invalid dependency entry `{d}`")));
                }
            }
            if packages.iter().any(|p: &LockedPackage| p.name == r.name) {
                return Err(err(format!("package `{}` appears more than once", r.name)));
            }
            packages.push(LockedPackage {
                name: r.name,
                version,
                source,
                checksum: r.checksum,
                dependencies: r.dependencies,
            });
        }
        packages.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(Lockfile { packages })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Lockfile {
        Lockfile {
            packages: vec![
                LockedPackage {
                    name: "zeta".into(),
                    version: Version::parse("1.2.3").unwrap(),
                    source: Source::Path("../zeta".into()),
                    checksum: None,
                    dependencies: vec![],
                },
                LockedPackage {
                    name: "mathkit".into(),
                    version: Version::parse("1.0.0").unwrap(),
                    source: Source::Registry("https://r.example.invalid".into()),
                    checksum: Some("ab".repeat(32)),
                    dependencies: vec!["b@1.0.0".into(), "a@1.0.0".into()],
                },
            ],
        }
    }

    #[test]
    fn render_is_sorted_and_round_trips() {
        let text = sample().render();
        assert!(text.find("mathkit").unwrap() < text.find("zeta").unwrap());
        assert!(text.contains("dependencies = [\"a@1.0.0\", \"b@1.0.0\"]"));
        let back = Lockfile::parse(&text).unwrap();
        assert_eq!(back.render(), text);
    }

    #[test]
    fn rejects_tampered_lockfiles() {
        let text = sample().render();
        assert!(Lockfile::parse(&text.replace(&"ab".repeat(32), "xyz")).is_err());
        assert!(Lockfile::parse(&text.replace("lock_version = 1", "lock_version = 2")).is_err());
        assert!(Lockfile::parse(&format!(
            "{text}\n[[package]]\nname = \"zeta\"\nversion = \"1.0.0\"\nsource = \"path+x\"\n"
        ))
        .is_err());
        assert!(Lockfile::parse(&text.replace("registry+", "git+")).is_err());
    }
}
